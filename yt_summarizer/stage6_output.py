log = get_logger(__name__)


@dataclass
class VideoSummary:
    video_id: str
    title: str
    author: str
    url: str
    summary: str
    key_points: List[str]
    timestamps: List[Dict[str, str]]
    mind_map: Dict
    model: str
    generated: bool
    created_at: str = field(default_factory=lambda: datetime.now().isoformat(timespec="seconds"))
    metrics: Dict = field(default_factory=dict)
    safety: Dict = field(default_factory=dict)
    warnings: List[str] = field(default_factory=list)
    diagnostics: Dict = field(default_factory=dict)

    def to_dict(self) -> Dict:
        return {
            "video": {
                "video_id": self.video_id,
                "title": self.title,
                "author": self.author,
                "url": self.url,
            },
            "created_at": self.created_at,
            "model": self.model,
            "generated_by_llm": self.generated,
            "summary": self.summary,
            "key_points": self.key_points,
            "timestamps": self.timestamps,
            "mind_map": self.mind_map,
            "metrics": self.metrics,
            "safety": self.safety,
            "warnings": self.warnings,
            "diagnostics": self.diagnostics,
        }


def _timestamp_link(url: str, time_label: str) -> str:
    """Turn mm:ss into a deep link into the video when the URL allows it."""
    parts = [int(p) for p in time_label.split(":") if p.strip().isdigit()]
    if not parts or not url.startswith("http"):
        return time_label
    seconds = 0
    for part in parts:
        seconds = seconds * 60 + part
    separator = "&" if "?" in url else "?"
    return "[%s](%s%st=%ds)" % (time_label, url, separator, seconds)


def assemble(doc: VideoDocument, result: SummaryResult) -> VideoSummary:
    return VideoSummary(
        video_id=doc.video_id,
        title=doc.title,
        author=doc.author,
        url=doc.url,
        summary=result.summary,
        key_points=result.key_points,
        timestamps=result.timestamps,
        mind_map=result.mind_map,
        model=result.model,
        generated=result.generated,
        warnings=list(result.warnings),
    )


def to_markdown(summary: VideoSummary) -> str:
    lines: List[str] = ["# %s" % summary.title, ""]
    lines.append("**Channel:** %s  " % summary.author)
    lines.append("**Source:** %s  " % summary.url)
    lines.append("**Model:** %s  " % summary.model)
    lines.append("**Generated:** %s" % summary.created_at)
    lines.append("")

    if not summary.generated:
        lines.append(
            "> **Offline fallback output.** These sentences were extracted from the "
            "transcript, not generated by a model. Not representative of the system's "
            "intended output."
        )
        lines.append("")

    lines += ["## Summary", "", summary.summary or "_No summary returned._", ""]

    lines += ["## Key points", ""]
    if summary.key_points:
        lines += ["- %s" % point for point in summary.key_points]
    else:
        lines.append("_None returned._")
    lines.append("")

    lines += ["## Timestamps", ""]
    if summary.timestamps:
        lines += ["| Time | Topic |", "| --- | --- |"]
        for item in summary.timestamps:
            lines.append(
                "| %s | %s |" % (_timestamp_link(summary.url, item["time"]), item.get("topic", ""))
            )
    else:
        lines.append("_None returned._")
    lines.append("")

    lines += ["## Mind map", "", "```mermaid", to_mermaid(summary.mind_map), "```", ""]

    if summary.metrics:
        lines += ["## Evaluation", "", "| Metric | Value |", "| --- | --- |"]
        for name, value in summary.metrics.items():
            if isinstance(value, float):
                lines.append("| %s | %.3f |" % (name.replace("_", " ").title(), value))
            else:
                lines.append("| %s | %s |" % (name.replace("_", " ").title(), value))
        lines.append("")

    if summary.warnings:
        lines += ["## Warnings", ""] + ["- %s" % w for w in summary.warnings] + [""]

    return "\n".join(lines)


def _mermaid_safe(text: str) -> str:
    cleaned = re.sub(r"[\"\[\](){}|]", "", str(text)).strip()
    return cleaned[:60] or "node"


def to_mermaid(mind_map: Dict) -> str:
    root = _mermaid_safe(mind_map.get("root", "Video"))
    lines = ["mindmap", "  root((%s))" % root]
    for i, branch in enumerate(mind_map.get("branches", []) or []):
        if isinstance(branch, str):
            lines.append("    %s" % _mermaid_safe(branch))
            continue
        lines.append("    %s" % _mermaid_safe(branch.get("name", "Branch %d" % (i + 1))))
        for child in branch.get("children", []) or []:
            lines.append("      %s" % _mermaid_safe(child))
    return "\n".join(lines)


