@dataclass
class CourseReport:
    title: str
    source: str
    videos: List[VideoSummary]
    overview: str
    themes: List[Dict]
    progression: str
    study_order: List[Dict]
    key_takeaways: List[str]
    model: str
    generated: bool
    skipped: List[Dict] = field(default_factory=list)
    metrics: Dict = field(default_factory=dict)
    warnings: List[str] = field(default_factory=list)
    diagnostics: Dict = field(default_factory=dict)
    created_at: str = field(
        default_factory=lambda: datetime.now().isoformat(timespec="seconds"))

    def to_dict(self) -> Dict:
        return {
            "course": {"title": self.title, "source": self.source,
                       "video_count": len(self.videos)},
            "created_at": self.created_at,
            "model": self.model,
            "generated_by_llm": self.generated,
            "overview": self.overview,
            "themes": self.themes,
            "progression": self.progression,
            "study_order": self.study_order,
            "key_takeaways": self.key_takeaways,
            "videos": [v.to_dict() for v in self.videos],
            "skipped": self.skipped,
            "metrics": self.metrics,
            "warnings": self.warnings,
            "diagnostics": self.diagnostics,
        }


def _video_label(report: "CourseReport", number: int) -> str:
    for v in report.videos:
        if v.diagnostics.get("course_index") == number:
            return v.title
    return "Video %d" % number


def course_to_markdown(report: CourseReport) -> str:
    lines: List[str] = ["# %s" % report.title, ""]
    lines.append("**Videos:** %d  " % len(report.videos))
    lines.append("**Source:** %s  " % report.source)
    lines.append("**Model:** %s  " % report.model)
    lines.append("**Generated:** %s" % report.created_at)
    lines.append("")

    if not report.generated:
        lines += ["> **Offline fallback output.** The per-video summaries were "
                  "concatenated rather than synthesised by a model.", ""]

    lines += ["## Course overview", "", report.overview or "_None returned._", ""]

    if report.progression:
        lines += ["## How the videos build up", "", report.progression, ""]

    if report.themes:
        lines += ["## Themes across the course", "", "| Theme | Videos | Detail |",
                  "| --- | --- | --- |"]
        for theme in report.themes:
            vids = ", ".join("V%d" % v for v in theme.get("videos", [])) or "—"
            lines.append("| %s | %s | %s |" % (theme["name"], vids,
                                               theme.get("detail", "")))
        lines.append("")

    if report.key_takeaways:
        lines += ["## Key takeaways", ""]
        lines += ["- %s" % t for t in report.key_takeaways]
        lines.append("")

    if report.study_order:
        lines += ["## Suggested order", ""]
        for i, step in enumerate(report.study_order, 1):
            label = _video_label(report, step["video"])
            why = (" — %s" % step["why"]) if step.get("why") else ""
            lines.append("%d. **V%d %s**%s" % (i, step["video"], label, why))
        lines.append("")

    lines += ["---", "", "## Per-video summaries", ""]
    for video in report.videos:
        number = video.diagnostics.get("course_index", 0)
        lines += ["### V%d — %s" % (number, video.title), ""]
        lines.append("%s  " % video.url)
        lines.append("")
        lines.append(video.summary or "_No summary returned._")
        lines.append("")
        if video.key_points:
            lines += ["- %s" % p for p in video.key_points] + [""]
        if video.timestamps:
            lines += ["| Time | Topic |", "| --- | --- |"]
            for item in video.timestamps:
                lines.append("| %s | %s |" % (
                    _timestamp_link(video.url, item["time"]), item.get("topic", "")))
            lines.append("")

    if report.skipped:
        lines += ["## Videos skipped", ""]
        lines += ["- %s — %s" % (s["url"], s["reason"]) for s in report.skipped]
        lines.append("")

    if report.metrics:
        lines += ["## Evaluation (course average)", "", "| Metric | Value |",
                  "| --- | --- |"]
        for name, value in report.metrics.items():
            if isinstance(value, float):
                lines.append("| %s | %.3f |" % (name.replace("_", " ").title(), value))
            else:
                lines.append("| %s | %s |" % (name.replace("_", " ").title(), value))
        lines.append("")

    if report.warnings:
        lines += ["## Warnings", ""] + ["- %s" % w for w in report.warnings] + [""]

    return "\n".join(lines)


def export_course(report: CourseReport,
                  directory: Optional[Path] = None) -> Dict[str, Path]:
    directory = Path(directory or settings.export_dir)
    directory.mkdir(parents=True, exist_ok=True)
    stem = "course_%s" % datetime.now().strftime("%Y%m%d_%H%M%S")

    paths = {
        "markdown": directory / ("%s.md" % stem),
        "json": directory / ("%s.json" % stem),
    }
    paths["markdown"].write_text(course_to_markdown(report), encoding="utf-8")
    paths["json"].write_text(
        json.dumps(report.to_dict(), indent=2, ensure_ascii=False), encoding="utf-8")
    log.info("Course exported to %s", directory)
    return paths


def export(summary: VideoSummary, directory: Optional[Path] = None) -> Dict[str, Path]:
    directory = Path(directory or settings.export_dir)
    directory.mkdir(parents=True, exist_ok=True)
    stem = "%s_%s" % (summary.video_id, datetime.now().strftime("%Y%m%d_%H%M%S"))

    paths = {
        "markdown": directory / ("%s.md" % stem),
        "json": directory / ("%s.json" % stem),
        "mindmap": directory / ("%s.mmd" % stem),
    }
    paths["markdown"].write_text(to_markdown(summary), encoding="utf-8")
    paths["json"].write_text(
        json.dumps(summary.to_dict(), indent=2, ensure_ascii=False), encoding="utf-8"
    )
    paths["mindmap"].write_text(to_mermaid(summary.mind_map), encoding="utf-8")

    log.info("Exported to %s", directory)
    return paths
